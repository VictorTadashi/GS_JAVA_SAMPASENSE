CREATE TABLE TB_SS_PONTO_MONITORADO (
    ID_PONTO            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_PONTO            VARCHAR2(100) NOT NULL,
    TP_PONTO            VARCHAR2(20)  NOT NULL,
    NM_BAIRRO           VARCHAR2(80)  NOT NULL,
    NR_LATITUDE         NUMBER(10,7)  NOT NULL,
    NR_LONGITUDE        NUMBER(10,7)  NOT NULL,
    ST_CRITICO          NUMBER(1)     DEFAULT 0 NOT NULL,
    VL_LIMITE_CHUVA_MM  NUMBER(6,2)   NOT NULL,
    VL_LIMITE_NIVEL_CM  NUMBER(6,2)   NOT NULL,
    VL_LIMITE_SUBIDA_CM NUMBER(6,2)   NOT NULL,
    CONSTRAINT PK_SS_PONTO PRIMARY KEY (ID_PONTO),
    CONSTRAINT CK_SS_PONTO_TIPO CHECK (TP_PONTO IN ('VALE', 'TUNEL')),
    CONSTRAINT CK_SS_PONTO_CRITICO CHECK (ST_CRITICO IN (0, 1))
);

CREATE TABLE TB_SS_SENSOR (
    ID_SENSOR     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CD_SENSOR     VARCHAR2(30) NOT NULL,
    TP_SENSOR     VARCHAR2(20) NOT NULL,
    ST_SENSOR     VARCHAR2(20) NOT NULL,
    DT_INSTALACAO DATE         NOT NULL,
    ID_PONTO      NUMBER       NOT NULL,
    CONSTRAINT PK_SS_SENSOR PRIMARY KEY (ID_SENSOR),
    CONSTRAINT UK_SS_SENSOR_CODIGO UNIQUE (CD_SENSOR),
    CONSTRAINT CK_SS_SENSOR_TIPO CHECK (TP_SENSOR IN ('PLUVIOMETRO', 'NIVEL_AGUA')),
    CONSTRAINT CK_SS_SENSOR_STATUS CHECK (ST_SENSOR IN ('ATIVO', 'INATIVO', 'MANUTENCAO'))
);

CREATE TABLE TB_SS_LEITURA (
    ID_LEITURA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_SENSOR  NUMBER       NOT NULL,
    VL_LEITURA NUMBER(8,2)  NOT NULL,
    DT_LEITURA TIMESTAMP    NOT NULL,
    CONSTRAINT PK_SS_LEITURA PRIMARY KEY (ID_LEITURA),
    CONSTRAINT CK_SS_LEITURA_VALOR CHECK (VL_LEITURA >= 0)
);

CREATE TABLE TB_SS_EVENTO_ALAGAMENTO (
    ID_EVENTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_PONTO  NUMBER       NOT NULL,
    NV_RISCO  VARCHAR2(20) NOT NULL,
    ST_EVENTO VARCHAR2(20) NOT NULL,
    DT_INICIO TIMESTAMP    NOT NULL,
    DT_FIM    TIMESTAMP,
    CONSTRAINT PK_SS_EVENTO PRIMARY KEY (ID_EVENTO),
    CONSTRAINT CK_SS_EVENTO_NIVEL CHECK (NV_RISCO IN ('NORMAL', 'ATENCAO', 'ALERTA', 'BLOQUEIO')),
    CONSTRAINT CK_SS_EVENTO_STATUS CHECK (ST_EVENTO IN ('ABERTO', 'ENCERRADO'))
);

CREATE TABLE TB_SS_ALERTA (
    ID_ALERTA   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_EVENTO   NUMBER        NOT NULL,
    TP_CANAL    VARCHAR2(30)  NOT NULL,
    NV_RISCO    VARCHAR2(20)  NOT NULL,
    DS_MENSAGEM VARCHAR2(255) NOT NULL,
    DT_ALERTA   TIMESTAMP     NOT NULL,
    CONSTRAINT PK_SS_ALERTA PRIMARY KEY (ID_ALERTA),
    CONSTRAINT CK_SS_ALERTA_CANAL CHECK (TP_CANAL IN
        ('PAINEL_TOTEM', 'SIRENE', 'WIFI_EMERGENCIA', 'CELL_BROADCAST', 'WHATSAPP', 'SMS', 'SEMAFORO'))
);

CREATE TABLE TB_SS_CONFIRMACAO_CIDADA (
    ID_CONFIRMACAO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_EVENTO      NUMBER       NOT NULL,
    TP_CONFIRMACAO VARCHAR2(20) NOT NULL,
    DT_CONFIRMACAO TIMESTAMP    NOT NULL,
    CONSTRAINT PK_SS_CONFIRMACAO PRIMARY KEY (ID_CONFIRMACAO),
    CONSTRAINT CK_SS_CONFIRMACAO_TIPO CHECK (TP_CONFIRMACAO IN ('ALAGOU', 'BAIXOU'))
);

CREATE TABLE TB_SS_PONTO_SEGURO (
    ID_PONTO_SEGURO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_PONTO_SEGURO VARCHAR2(100) NOT NULL,
    TP_PONTO_SEGURO VARCHAR2(20)  NOT NULL,
    DS_ENDERECO     VARCHAR2(150) NOT NULL,
    NR_LATITUDE     NUMBER(10,7)  NOT NULL,
    NR_LONGITUDE    NUMBER(10,7)  NOT NULL,
    ST_ACESSIVEL    NUMBER(1)     DEFAULT 0 NOT NULL,
    NR_CAPACIDADE   NUMBER(6),
    ID_PONTO        NUMBER        NOT NULL,
    CONSTRAINT PK_SS_PONTO_SEGURO PRIMARY KEY (ID_PONTO_SEGURO),
    CONSTRAINT CK_SS_PSEGURO_TIPO CHECK (TP_PONTO_SEGURO IN ('ESCOLA', 'UBS', 'COMERCIO', 'OUTRO')),
    CONSTRAINT CK_SS_PSEGURO_ACESSIVEL CHECK (ST_ACESSIVEL IN (0, 1))
);

CREATE TABLE TB_SS_RECOMENDACAO_BLOQUEIO (
    ID_BLOQUEIO  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_EVENTO    NUMBER       NOT NULL,
    ST_BLOQUEIO  VARCHAR2(20) NOT NULL,
    NM_OPERADOR  VARCHAR2(60),
    DT_CRIACAO   TIMESTAMP    NOT NULL,
    DT_DECISAO   TIMESTAMP,
    CONSTRAINT PK_SS_BLOQUEIO PRIMARY KEY (ID_BLOQUEIO),
    CONSTRAINT CK_SS_BLOQUEIO_STATUS CHECK (ST_BLOQUEIO IN ('PENDENTE', 'CONFIRMADO', 'RECUSADO', 'AUTOMATICO'))
);

CREATE TABLE TB_SS_USUARIO (
    ID_USUARIO  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_USUARIO  VARCHAR2(80)  NOT NULL,
    DS_EMAIL    VARCHAR2(120) NOT NULL,
    DS_SENHA    VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_SS_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_SS_USUARIO_EMAIL UNIQUE (DS_EMAIL)
);

-- ===== Chaves estrangeiras =====
ALTER TABLE TB_SS_SENSOR ADD CONSTRAINT FK_SS_SENSOR_PONTO
    FOREIGN KEY (ID_PONTO) REFERENCES TB_SS_PONTO_MONITORADO (ID_PONTO);

ALTER TABLE TB_SS_LEITURA ADD CONSTRAINT FK_SS_LEITURA_SENSOR
    FOREIGN KEY (ID_SENSOR) REFERENCES TB_SS_SENSOR (ID_SENSOR);

ALTER TABLE TB_SS_EVENTO_ALAGAMENTO ADD CONSTRAINT FK_SS_EVENTO_PONTO
    FOREIGN KEY (ID_PONTO) REFERENCES TB_SS_PONTO_MONITORADO (ID_PONTO);

ALTER TABLE TB_SS_ALERTA ADD CONSTRAINT FK_SS_ALERTA_EVENTO
    FOREIGN KEY (ID_EVENTO) REFERENCES TB_SS_EVENTO_ALAGAMENTO (ID_EVENTO);

ALTER TABLE TB_SS_CONFIRMACAO_CIDADA ADD CONSTRAINT FK_SS_CONFIRMACAO_EVENTO
    FOREIGN KEY (ID_EVENTO) REFERENCES TB_SS_EVENTO_ALAGAMENTO (ID_EVENTO);

ALTER TABLE TB_SS_PONTO_SEGURO ADD CONSTRAINT FK_SS_PSEGURO_PONTO
    FOREIGN KEY (ID_PONTO) REFERENCES TB_SS_PONTO_MONITORADO (ID_PONTO);

ALTER TABLE TB_SS_RECOMENDACAO_BLOQUEIO ADD CONSTRAINT FK_SS_BLOQUEIO_EVENTO
    FOREIGN KEY (ID_EVENTO) REFERENCES TB_SS_EVENTO_ALAGAMENTO (ID_EVENTO);
